-- ============================================================================
-- DIMENSIONES
-- ============================================================================

CREATE TABLE dim_tiempo (
    id_tiempo       SERIAL PRIMARY KEY,
    fecha           DATE NOT NULL UNIQUE,
    anio            INTEGER NOT NULL,
    mes             INTEGER NOT NULL CHECK (mes BETWEEN 1 AND 12),
    mes_nombre      VARCHAR(20) NOT NULL,
    dia             INTEGER NOT NULL CHECK (dia BETWEEN 1 AND 31),
    dia_semana      VARCHAR(15) NOT NULL,
    trimestre       INTEGER NOT NULL CHECK (trimestre BETWEEN 1 AND 4),
    semestre        INTEGER NOT NULL CHECK (semestre BETWEEN 1 AND 2),
    es_fin_semana   BOOLEAN DEFAULT FALSE
);

CREATE TABLE dim_estudiante (
    id_estudiante       SERIAL PRIMARY KEY,
    codigo_estudiante   VARCHAR(20) NOT NULL UNIQUE,
    nombre_completo     VARCHAR(150) NOT NULL,
    genero              VARCHAR(20) NOT NULL,
    fecha_nacimiento    DATE,
    ciudad_residencia   VARCHAR(100),
    provincia           VARCHAR(100)
);

CREATE TABLE dim_docente (
    id_docente          SERIAL PRIMARY KEY,
    codigo_docente      VARCHAR(20) NOT NULL UNIQUE,
    nombre_completo     VARCHAR(150) NOT NULL,
    nivel_estudios      VARCHAR(50),
    especialidad        VARCHAR(100),
    tipo_contrato       VARCHAR(50)
);

CREATE TABLE dim_curso (
    id_curso            SERIAL PRIMARY KEY,
    codigo_curso        VARCHAR(20) NOT NULL UNIQUE,
    nombre_curso        VARCHAR(150) NOT NULL,
    creditos            INTEGER NOT NULL CHECK (creditos > 0),
    area_conocimiento   VARCHAR(100),
    modalidad           VARCHAR(50) NOT NULL DEFAULT 'Presencial'
);

CREATE TABLE dim_programa (
    id_programa         SERIAL PRIMARY KEY,
    codigo_programa     VARCHAR(20) NOT NULL UNIQUE,
    nombre_programa     VARCHAR(150) NOT NULL,
    facultad            VARCHAR(150) NOT NULL,
    nivel_formacion     VARCHAR(50) NOT NULL,
    director_programa   VARCHAR(150)
);

CREATE TABLE dim_geografia (
    id_geografia    SERIAL PRIMARY KEY,
    ciudad          VARCHAR(100) NOT NULL,
    provincia       VARCHAR(100) NOT NULL,
    pais            VARCHAR(100) NOT NULL DEFAULT 'Ecuador'
);

-- ============================================================================
-- TABLA DE HECHOS
-- Grano: Una inscripción de un estudiante en un curso, dictado por un
--         docente, dentro de un programa, en un periodo específico.
-- ============================================================================

CREATE TABLE fact_inscripcion (
    id_fact             SERIAL PRIMARY KEY,
    id_tiempo           INTEGER NOT NULL REFERENCES dim_tiempo(id_tiempo),
    id_estudiante       INTEGER NOT NULL REFERENCES dim_estudiante(id_estudiante),
    id_curso            INTEGER NOT NULL REFERENCES dim_curso(id_curso),
    id_docente          INTEGER NOT NULL REFERENCES dim_docente(id_docente),
    id_programa         INTEGER NOT NULL REFERENCES dim_programa(id_programa),
    id_ubicacion        INTEGER NOT NULL REFERENCES dim_geografia(id_geografia),
    cantidad_inscripciones  INTEGER NOT NULL DEFAULT 1,
    monto_ingreso       DECIMAL(12,2) NOT NULL DEFAULT 0.00
);

-- ============================================================================
-- ÍNDICES
-- ============================================================================

CREATE INDEX idx_fact_tiempo ON fact_inscripcion(id_tiempo);
CREATE INDEX idx_fact_estudiante ON fact_inscripcion(id_estudiante);
CREATE INDEX idx_fact_curso ON fact_inscripcion(id_curso);
CREATE INDEX idx_fact_docente ON fact_inscripcion(id_docente);
CREATE INDEX idx_fact_programa ON fact_inscripcion(id_programa);
CREATE INDEX idx_fact_ubicacion ON fact_inscripcion(id_ubicacion);
CREATE INDEX idx_fact_tiempo_curso ON fact_inscripcion(id_tiempo, id_curso);
CREATE INDEX idx_dim_tiempo_anio_mes ON dim_tiempo(anio, mes);
CREATE INDEX idx_dim_geografia_ciudad ON dim_geografia(ciudad);
CREATE INDEX idx_dim_curso_nombre ON dim_curso(nombre_curso);
CREATE INDEX idx_dim_programa_nombre ON dim_programa(nombre_programa);

