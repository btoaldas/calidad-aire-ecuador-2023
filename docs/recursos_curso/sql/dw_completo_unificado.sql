-- P1: ¿Cuánto ingreso generó cada curso por mes y año?
CREATE OR REPLACE VIEW v_ingreso_por_curso_mes AS
SELECT
    t.anio,
    t.mes,
    t.mes_nombre,
    c.nombre_curso,
    c.area_conocimiento,
    COUNT(*) AS total_inscripciones,
    SUM(f.monto_ingreso) AS ingreso_total,
    AVG(f.monto_ingreso) AS ingreso_promedio
FROM fact_inscripcion f
JOIN dim_tiempo t ON f.id_tiempo = t.id_tiempo
JOIN dim_curso c ON f.id_curso = c.id_curso
GROUP BY t.anio, t.mes, t.mes_nombre, c.nombre_curso, c.area_conocimiento
ORDER BY t.anio, t.mes, ingreso_total DESC;

-- P2: ¿Cuántas inscripciones tiene cada programa académico?
CREATE OR REPLACE VIEW v_inscripciones_por_programa AS
SELECT
    p.nombre_programa,
    p.facultad,
    p.nivel_formacion,
    COUNT(*) AS total_inscripciones,
    SUM(f.monto_ingreso) AS ingreso_total,
    COUNT(DISTINCT f.id_estudiante) AS estudiantes_unicos
FROM fact_inscripcion f
JOIN dim_programa p ON f.id_programa = p.id_programa
GROUP BY p.nombre_programa, p.facultad, p.nivel_formacion
ORDER BY total_inscripciones DESC;

-- P3: ¿Qué docente tiene más inscripciones en sus cursos?
CREATE OR REPLACE VIEW v_inscripciones_por_docente AS
SELECT
    d.nombre_completo AS nombre_docente,
    d.especialidad,
    d.tipo_contrato,
    COUNT(*) AS total_inscripciones,
    SUM(f.monto_ingreso) AS ingreso_generado,
    COUNT(DISTINCT f.id_estudiante) AS estudiantes_atendidos
FROM fact_inscripcion f
JOIN dim_docente d ON f.id_docente = d.id_docente
GROUP BY d.nombre_completo, d.especialidad, d.tipo_contrato
ORDER BY total_inscripciones DESC;

-- P4: ¿Cuántos estudiantes únicos se inscribieron por mes?
CREATE OR REPLACE VIEW v_estudiantes_unicos_por_mes AS
SELECT
    t.anio,
    t.mes,
    t.mes_nombre,
    COUNT(DISTINCT f.id_estudiante) AS estudiantes_unicos,
    COUNT(*) AS total_inscripciones,
    SUM(f.monto_ingreso) AS ingreso_total
FROM fact_inscripcion f
JOIN dim_tiempo t ON f.id_tiempo = t.id_tiempo
GROUP BY t.anio, t.mes, t.mes_nombre
ORDER BY t.anio, t.mes;

-- P5: ¿Qué ciudad aporta más ingresos?
CREATE OR REPLACE VIEW v_ingresos_por_ciudad AS
SELECT
    g.ciudad,
    g.provincia,
    COUNT(*) AS total_inscripciones,
    SUM(f.monto_ingreso) AS ingreso_total,
    AVG(f.monto_ingreso) AS ingreso_promedio,
    COUNT(DISTINCT f.id_estudiante) AS estudiantes_unicos
FROM fact_inscripcion f
JOIN dim_geografia g ON f.id_ubicacion = g.id_geografia
GROUP BY g.ciudad, g.provincia
ORDER BY ingreso_total DESC;

